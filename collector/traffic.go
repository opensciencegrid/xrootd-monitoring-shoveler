// The network scope of a transfer, published as "traffic_scope" on the WLCG
// record. It is the canonical topology answer: "site_internal_traffic" is
// derived from it (see siteInternalFromScope), so the two can never disagree.
//
// UNKNOWN is an answer of its own: the collector could not settle both ends,
// which differs from settling them and finding them apart. The values are
// uppercase network terms; the per-endpoint statuses in sitemap.go keep their
// own lowercase vocabulary.
const (
	TrafficScopeLAN     = "LAN"     // both ends resolved to the same RCSite
	TrafficScopeWAN     = "WAN"     // both ends resolved, to different RCSites
	TrafficScopeUnknown = "UNKNOWN" // at least one end was not resolved
)

// The signals that mark an operation as generated by XRootD itself rather than
// by an end user. They are the "signal" label on shoveler_traffic_xrootd_internal
// and are a fixed set, so the label stays bounded.
const (
	TrafficSignalInternalUser = "internal_user" // the account is a system account (wlcg.traffic_internal_users)
	TrafficSignalJobAgent     = "job_agent"     // the account is a numeric job-agent id in the configured range
	TrafficSignalReplication  = "replication"   // protocol, appinfo or path names a replication operation
)

// Defaults for the XRootD-internal rules, from the MonALISA xrootd collector's
// isActualUser (lia/Monitor/modules/monXrootd.java): an operation is not a real
// user's when the account is "root", a single job-agent digit 1-8, or "daemon"
// running a "/replicate:" path.
var (
	// DefaultTrafficInternalUsers are the accounts XRootD uses for its own work.
	DefaultTrafficInternalUsers = []string{"root"}

	// DefaultTrafficReplicationPrefixes match a replication operation. MonALISA
	// looks for "/replicate:" in the path; the protocol "replicate" counts too.
	DefaultTrafficReplicationPrefixes = []string{"replicate"}
)

// The XRootD job-agent/system accounts are reported as a bare number. MonALISA
// accepts a single digit 1-8; the range is configurable here.
const (
	DefaultTrafficJobAgents = "1-8"
	TrafficJobAgentsNone    = "none" // turns the job-agent rule off
)

// TrafficConfig holds the deployment-specific parts of the classification, so
// the rules are not buried in the classifier. It applies only in WLCG mode; see
// shoveler.WLCGConfig for the keys behind each field.
type TrafficConfig struct {
	// Enabled turns the classification on. It defaults to true, but takes effect
	// only while wlcg.enabled is on: the three fields are emitted on the WLCG
	// record only.
	Enabled bool

	// InternalUsers are accounts whose operations are XRootD's own work, matched
	// exactly against the account the 'u' stream reported. nil means
	// DefaultTrafficInternalUsers; an empty list turns the rule off.
	InternalUsers []string

	// JobAgents is the range of numeric job-agent accounts, "N" or "N-M",
	// matched when the account is all digits. Empty means
	// DefaultTrafficJobAgents, and "none" turns the rule off.
	JobAgents string

	// ReplicationPrefixes mark a replication operation: a protocol equal to the
	// prefix, or a "/"-separated segment of the appinfo or the path that starts
	// with the prefix and a colon. nil means
	// DefaultTrafficReplicationPrefixes; an empty list turns the rule off.
	ReplicationPrefixes []string

	// CaseSensitive matches accounts and replication prefixes exactly as written.
	// Default false: XRootD account names and protocols arrive in whatever case
	// the client used, and "Root" is the same account as "root".
	CaseSensitive bool
}

// withDefaults fills in the lists the operator said nothing about. The
// job-agent range has its default in jobAgentRange.
func (c TrafficConfig) withDefaults() TrafficConfig {
	if c.InternalUsers == nil {
		c.InternalUsers = DefaultTrafficInternalUsers
	}
	if c.ReplicationPrefixes == nil {
		c.ReplicationPrefixes = DefaultTrafficReplicationPrefixes
	}
	return c
}

// jobAgentRange returns the job-agent range in force. Empty is
// DefaultTrafficJobAgents. A value that does not parse, such as "off" or
// "false", turns the rule off and err says why: flagging a user's transfer as
// internal is the worse mistake. The rule is off when last < first.
func (c TrafficConfig) jobAgentRange() (first, last int, err error) {
	value := c.JobAgents
	if strings.TrimSpace(value) == "" {
		value = DefaultTrafficJobAgents
	}
	first, last, err = parseJobAgentRange(value)
	if err != nil {
		return 1, 0, err
	}
	return first, last, nil
}

// parseJobAgentRange reads "N", "N-M" or "none" into the bounds of the range.
// "none" returns last < first, which turns the rule off.
func parseJobAgentRange(value string) (first, last int, err error) {
	v := strings.TrimSpace(value)
	if strings.EqualFold(v, TrafficJobAgentsNone) {
		return 1, 0, nil
	}
	lo, hi, isRange := strings.Cut(v, "-")
	if first, err = strconv.Atoi(strings.TrimSpace(lo)); err != nil || first < 0 {
		return 0, 0, fmt.Errorf("job-agent range %q: want N, N-M or %q", value, TrafficJobAgentsNone)
	}
	last = first
	if isRange {
		if last, err = strconv.Atoi(strings.TrimSpace(hi)); err != nil || last < first {
			return 0, 0, fmt.Errorf("job-agent range %q: want N-M with M >= N", value)
		}
	}
	return first, last, nil
}

// trafficClassifier answers the one question "was this XRootD's own work?" from
// a record. It holds the normalized rules so each record costs only lookups.
type trafficClassifier struct {
	internalUsers       map[string]struct{}
	jobAgentMin         int
	jobAgentMax         int
	replicationPrefixes []string
	caseSensitive       bool

	// The path forms of each prefix, built once so matching a record allocates
	// nothing: "replicate:" at the start of a value and "/replicate:" inside it.
	replicationStarts   []string
	replicationSegments []string
}

// newTrafficClassifier compiles a TrafficConfig into a classifier, applying the
// defaults for anything left unset. The defaults live here rather than in the
// config layer so there is one copy of each, as with NormalizeVOOrder and
// NormalizeSiteResolutionOrder.
func newTrafficClassifier(cfg TrafficConfig) *trafficClassifier {
	cfg = cfg.withDefaults()

	c := &trafficClassifier{caseSensitive: cfg.CaseSensitive}
	c.jobAgentMin, c.jobAgentMax, _ = cfg.jobAgentRange()

	c.internalUsers = make(map[string]struct{}, len(cfg.InternalUsers))
	for _, user := range cfg.InternalUsers {
		if u := c.fold(user); u != "" {
			c.internalUsers[u] = struct{}{}
		}
	}

	c.replicationPrefixes = make([]string, 0, len(cfg.ReplicationPrefixes))
	for _, prefix := range cfg.ReplicationPrefixes {
		if p := c.fold(prefix); p != "" {
			c.replicationPrefixes = append(c.replicationPrefixes, p)
			c.replicationStarts = append(c.replicationStarts, p+":")
			c.replicationSegments = append(c.replicationSegments, "/"+p+":")
		}
	}

	return c
}

// fold normalizes a value for comparison: trimmed, and lowercased unless the
// operator asked for exact matching.
func (t *trafficClassifier) fold(value string) string {
	v := strings.TrimSpace(value)
	if t.caseSensitive {
		return v
	}
	return strings.ToLower(v)
}

// ClassifyXRootDInternal reports whether the record looks like XRootD's own
// work, and which signal said so. The signals are OR-ed and checked in a fixed
// order, so the reported one is the first that matched:
//
//  1. the account is a configured system account ("root")
//  2. the account is a numeric job-agent id in the configured range (1-8)
//  3. the protocol, appinfo or path names a replication operation ("replicate")
//
// Nothing else counts. A record whose account never reached the collector, or
// that carries none of these markers, is reported as false: the schema has no
// unknown state for it, and calling an ordinary user's transfer infrastructure
// traffic is the worse mistake.
func (t *trafficClassifier) ClassifyXRootDInternal(record *CollectorRecord) (internal bool, signal string) {
	if record == nil {
		return false, ""
	}

	// A record names its account in two places and the system accounts show up in
	// both, so both are judged (see recordAccounts).
	for _, account := range recordAccounts(record) {
		user := t.fold(account)
		if user == "" {
			continue
		}
		if _, ok := t.internalUsers[user]; ok {
			return true, TrafficSignalInternalUser
		}
		if t.isJobAgentID(user) {
			return true, TrafficSignalJobAgent
		}
	}

	// MonALISA looks for "/replicate:" in the dict info, which is the path for a
	// transfer and the appinfo for an application record; the protocol is checked
	// too so a replication protocol is caught on its own.
	if t.isReplicationProtocol(record.Protocol) ||
		t.isReplicationPath(record.AppInfo) ||
		t.isReplicationPath(record.Filename) {
		return true, TrafficSignalReplication
	}

	return false, ""
}

// recordAccounts returns the account names a record can be judged on, in a fixed
// array so classifying a record allocates nothing. Either may be empty.
//
// [0] is the account the 'u' stream reported alongside the protocol and host,
// and it is taken only when user info was actually correlated: without it the
// record carries a hex of the numeric user id (see BuildUserHex), which for a
// low id is indistinguishable from a job-agent account — a missing input, not a
// signal.
//
// [1] is what user_dn names. Despite the name that field is the auth stream's
// "n=" value, which in production is usually a mapped account rather than a
// distinguished name, and it is where the system accounts actually show up:
// "root" and "daemon" appear there on records whose "user" is an ordinary
// account or a hex fallback. It needs no correlation guard of its own, since a
// record only has a DN when its user info was correlated.
func recordAccounts(record *CollectorRecord) [2]string {
	accounts := [2]string{}
	if record.userInfoKnown {
		accounts[0] = record.User
	}
	accounts[1] = accountFromUserDN(record.UserDN)
	return accounts
}

// accountFromUserDN reads the account out of a user_dn value: the CN when it is
// a real distinguished name, and the value itself when it is a bare account
// name, which is the common case.
//
// This is deliberately a superset of what ConvertToWLCG publishes as "user",
// which takes the CN and nothing else: a bare account is an identity worth
// classifying on even though the WLCG record does not republish it there. The
// record still carries it, as user_dn.
func accountFromUserDN(dn string) string {
	value := strings.TrimSpace(dn)
	if value == "" {
		return ""
	}
	if idx := strings.LastIndex(value, "CN="); idx >= 0 {
		return strings.TrimSpace(value[idx+len("CN="):])
	}
	// A DN with no CN names no account; anything without DN punctuation is the
	// account itself.
	if strings.ContainsAny(value, "=/") {
		return ""
	}
	return value
}

// isJobAgentID reports whether an account is one of the numeric job-agent ids.
// The account must be all digits: XRootD reports these agents as a bare number,
// so anything else is a name that merely starts with one.
func (t *trafficClassifier) isJobAgentID(user string) bool {
	if t.jobAgentMax < t.jobAgentMin {
		return false
	}

	id := 0
	for _, r := range user {
		if r < '0' || r > '9' {
			return false
		}
		digit := int(r - '0')
		// Checked before the multiply, so a long digit string stops here
		// instead of wrapping around.
		if id > (t.jobAgentMax-digit)/10 {
			return false
		}
		id = id*10 + digit
		if id > t.jobAgentMax {
			return false
		}
	}
	if user == "" {
		return false
	}

	return id >= t.jobAgentMin
}

// isReplicationProtocol reports whether the protocol is a replication marker
// ("replicate").
func (t *trafficClassifier) isReplicationProtocol(protocol string) bool {
	p := t.fold(protocol)
	for _, prefix := range t.replicationPrefixes {
		if p == prefix {
			return true
		}
	}
	return false
}

// isReplicationPath reports whether a path or appinfo names a replication
// operation: one of its "/"-separated segments starts with a marker and a colon,
// as in "/replicate:xyz". Folders such as "replicate" or "replicated_runs" stay
// user traffic.
func (t *trafficClassifier) isReplicationPath(value string) bool {
	if len(t.replicationStarts) == 0 {
		return false
	}
	v := t.fold(value)
	if v == "" {
		return false
	}

	for i, start := range t.replicationStarts {
		if strings.HasPrefix(v, start) || strings.Contains(v, t.replicationSegments[i]) {
			return true
		}
	}
	return false
}

// classifyTrafficScope turns the two per-endpoint site resolutions into the
// record's scope. Both ends must have resolved for the scope to be anything but
// UNKNOWN: an ambiguous match names a site but is explicitly a guess (see
// SiteRegistry.resolveHost), and guessing here would produce a definite LAN or
// WAN from an undecided endpoint.
func classifyTrafficScope(srcSite, srcStatus, dstSite, dstStatus string) string {
	if !isResolvedSiteStatus(srcStatus) || !isResolvedSiteStatus(dstStatus) {
		return TrafficScopeUnknown
	}
	// Defence in depth: a resolved status always carries a site name.
	if srcSite == "" || dstSite == "" {
		return TrafficScopeUnknown
	}
	// local_site and site.overrides are typed by the operator and the other
	// methods name sites from CRIC, so "cern-prod" and "CERN-PROD" are one site.
	if strings.EqualFold(strings.TrimSpace(srcSite), strings.TrimSpace(dstSite)) {
		return TrafficScopeLAN
	}
	return TrafficScopeWAN
}

// siteInternalFromScope derives site_internal_traffic from the scope, which is
// the only place the two are related: LAN is internal, WAN is not, and an
// unresolved topology has no answer at all (nil, so the field is left off the
// record).
func siteInternalFromScope(scope string) *bool {
	internal := true
	external := false
	switch scope {
	case TrafficScopeLAN:
		return &internal
	case TrafficScopeWAN:
		return &external
	default:
		return nil
	}
}

// trafficRecordEnricher stamps the scope and the XRootD-internal verdict on a
// record. It must run AFTER siteRecordEnricher, whose src/dst resolution the
// scope is read from.
//
// The two classifications are independent: a record can be LAN and internal,
// LAN and a user's, WAN and internal, or WAN and a user's. Neither filters the
// other, and an UNKNOWN scope does not stop the origin from being classified.
type trafficRecordEnricher struct {
	classifier *trafficClassifier

	// wlcgOnly gates the work, like the site enricher: the fields are emitted on
	// WLCG records only, so classifying anything else would be thrown away. nil
	// classifies every record, which is what the unit tests want.
	wlcgOnly func(*CollectorRecord) bool
}

func (t *trafficRecordEnricher) Name() string { return "traffic" }

func (t *trafficRecordEnricher) Enrich(_ context.Context, record *CollectorRecord) {
	if record == nil || t.classifier == nil {
		return
	}
	if t.wlcgOnly != nil && !t.wlcgOnly(record) {
		return
	}

	scope := classifyTrafficScope(record.srcSite, record.srcSiteStatus, record.dstSite, record.dstSiteStatus)
	internal, signal := t.classifier.ClassifyXRootDInternal(record)

	record.trafficScope = scope
	record.xrootdInternal = internal

	trafficScopeTotal.WithLabelValues(scope).Inc()
	if internal {
		trafficXRootDInternal.WithLabelValues(signal).Inc()
	}
}

// logTrafficRules states the rules in force once at startup, the way the site
// resolver logs its order. Per-record reasons are not logged: there are
// millions of records and the account is user information.
func logTrafficRules(logger *logrus.Logger, cfg TrafficConfig) {
	if logger == nil {
		return
	}
	// The rules as they are actually applied: an unset one is the default, and
	// that is what an operator needs to see.
	cfg = cfg.withDefaults()
	first, last, err := cfg.jobAgentRange()
	if err != nil {
		logger.Warnf("traffic: wlcg.traffic_job_agents: %v; the job-agent rule is off", err)
	}
	jobAgents := fmt.Sprintf("%d-%d", first, last)
	if last < first {
		jobAgents = TrafficJobAgentsNone
	}
	logger.Infof("traffic: xrootd-internal rules: users %v, job-agent ids %s, replication prefixes %v (case-sensitive %t)",
		cfg.InternalUsers, jobAgents, cfg.ReplicationPrefixes, cfg.CaseSensitive)
}
